const { withInfoPlist, withAppDelegate, withXcodeProject, withDangerousMod, IOSConfig } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Adopt the UIScene lifecycle (required by UIKit for apps linked against the
 * iOS 27 SDK — without it the app traps at launch with
 * ___UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption).
 *
 * Expo SDK 53+'s template still builds the UIWindow in AppDelegate. This plugin
 *  1. declares UIApplicationSceneManifest in Info.plist (single scene),
 *  2. adds SceneDelegate.swift, which creates the UIWindow from the
 *     UIWindowScene and starts React Native in it (same RCTReactNativeFactory
 *     call the template made), and forwards URL / user-activity events to
 *     React Native's Linking + Expo's app-delegate subscribers,
 *  3. strips the window creation from AppDelegate.swift and keeps the
 *     launchOptions so the scene can hand them to React Native.
 */

const SCENE_DELEGATE_FILE = 'SceneDelegate.swift';

const SCENE_DELEGATE_SOURCE = `import UIKit
import Expo
import React

/// UIScene lifecycle entry point. Generated by plugins/withSceneLifecycle.js —
/// do not edit the copy inside ios/, edit the plugin instead.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // startReactNative sets the root view controller and makes the window key.
    appDelegate.reactNativeFactory?.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: appDelegate.launchOptions)

    // Cold start from a URL or a user activity (universal link).
    for context in connectionOptions.urlContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
    for activity in connectionOptions.userActivities {
      _ = appDelegate.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  // Linking API (replaces application(_:open:options:) under the scene lifecycle)
  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    for context in URLContexts {
      _ = appDelegate.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  // Universal Links
  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    guard let appDelegate = UIApplication.shared.delegate as? AppDelegate else { return }
    _ = appDelegate.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (cfg) => {
    let src = cfg.modResults.contents;
    if (cfg.modResults.language !== 'swift') {
      throw new Error('withSceneLifecycle: expected a Swift AppDelegate (Expo SDK 53+).');
    }
    if (src.includes('withSceneLifecycle')) return cfg; // already applied

    // 1. Keep the launch options for the scene delegate.
    const windowDecl = 'var window: UIWindow?\n';
    if (!src.includes(windowDecl)) throw new Error('withSceneLifecycle: AppDelegate window property not found');
    src = src.replace(
      windowDecl,
      windowDecl +
        '\n  // withSceneLifecycle: the UIWindow is created by SceneDelegate (UIScene lifecycle).\n' +
        '  // Launch options are kept so the scene can pass them to React Native.\n' +
        '  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n',
    );

    // 2. Remove the window creation + startReactNative call from didFinishLaunching.
    const windowBlock = /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n\s*factory\.startReactNative\(\n\s*withModuleName: "main",\n\s*in: window,\n\s*launchOptions: launchOptions\)\n#endif\n/;
    if (!windowBlock.test(src)) throw new Error('withSceneLifecycle: window creation block not found in AppDelegate.swift');
    src = src.replace(windowBlock, '    self.launchOptions = launchOptions\n');

    cfg.modResults.contents = src;
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    'ios',
    (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const dest = path.join(cfg.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE);
      fs.writeFileSync(dest, SCENE_DELEGATE_SOURCE);
      return cfg;
    },
  ]);

  return withXcodeProject(config, (cfg) => {
    const project = cfg.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const relPath = `${projectName}/${SCENE_DELEGATE_FILE}`;
    if (!project.hasFile(relPath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath: relPath,
        groupName: projectName,
        project,
      });
    }
    return cfg;
  });
}

module.exports = function withSceneLifecycle(config) {
  config = withSceneManifest(config);
  config = withSceneAppDelegate(config);
  config = withSceneDelegateFile(config);
  return config;
};
